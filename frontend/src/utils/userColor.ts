/**
 * Детерминированный цвет пользователя по user_id.
 *
 * Стабилен между устройствами и сессиями: зависит только от ID.
 * Возвращает hue в градусах. Соседние ID хорошо расходятся за счёт
 * золотого угла 137.508°.
 */
export function userHue(userId: number): number {
  return (userId * 137.508) % 360;
}
